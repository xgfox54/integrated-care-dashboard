import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import path from "node:path";
import test from "node:test";
import { assertDepartmentSourceEquality, completeDepartment } from "../build-detail-department.mjs";
import { buildBudgetPack } from "../build-budget-pack.mjs";
import { extractBudgetLines } from "../extract-budget-lines.mjs";
import { readZip } from "../../../lib/imports/zip.ts";
import { validateBudgetPack } from "../../../lib/imports/budget-pack.ts";

const json = file => JSON.parse(readFileSync(file, "utf8"));
const reportFile = process.env.BUDGET_DETAIL_DEPARTMENT_REPORT;
if (reportFile) test("welfare department is complete, source-identical, and independently validated", async () => {
  const report = json(reportFile);
  const sourceReport = json(report.source_report);
  const source = sourceReport.documents.find(document => document.id === report.source_id);
  assert.equal(source.status, "HELD");
  assert.ok(source.problems.length > 0);
  const full = extractBudgetLines(source.evidence_dir);
  const selection = completeDepartment(full, report.department, source.problems);
  const root = full.lines.find(line => line.level === "department" && line.name === report.department);
  const descendants = new Set([root.line_no]);
  for (const line of full.lines) if (descendants.has(line.parent_line_no)) descendants.add(line.line_no);
  assert.deepEqual(selection.lines, full.lines.filter(line => descendants.has(line.line_no)), "every original descendant must be included without mutation");
  assert.equal(selection.lines.length, 382);
  assert.equal(selection.summary.by_level.detail_project, 77);
  assert.equal(selection.summary.first_page, 31);
  assert.equal(selection.summary.last_page, 51);
  assert.equal(selection.lines[0].amount_thousand_krw, "48,150,480");
  const config = json(report.config);
  assert.match(config.documents[0].scope_text, /여성가족과 전체.*다른 부서는 제외/);
  assert.deepEqual(json(config.documents[0].lines_json), selection);
  const bytes = readFileSync(report.bundle);
  assert.equal(createHash("sha256").update(bytes).digest("hex"), report.sha256);
  assert.equal((await buildBudgetPack(config)).sha256, report.sha256);
  const entries = await readZip(bytes);
  const manifest = JSON.parse(new TextDecoder().decode(entries.find(entry => entry.path === "manifest.json").bytes));
  assert.equal((await validateBudgetPack(entries, manifest)).ok, true);
  const provenance = json(path.join(path.dirname(report.config), "provenance.json"));
  assert.deepEqual(provenance.source_attachment_problems, source.problems);
  for (const problem of source.problems) assert.throws(() => completeDepartment(full, report.department, [{ ...problem, line_no: root.line_no }]), /entire selected department/);
  assert.throws(() => completeDepartment(full, report.department, [{ code: "UNKNOWN_GLOBAL_PROBLEM" }]), /entire selected department/);
  assert.throws(() => completeDepartment(full, "청년정책과", source.problems), /entire selected department/);
  const removedItem = selection.lines.find(line => line.level === "item" && line.checks.formula === "match" && !selection.lines.some(child => child.parent_line_no === line.line_no));
  assert.ok(removedItem);
  const incomplete = { ...selection, lines: selection.lines.filter(line => line !== removedItem) };
  assert.throws(() => assertDepartmentSourceEquality(incomplete, full, report.department, source.problems), /DEPARTMENT_SOURCE_SUBTREE_CHANGED/, "even deletion of an object's only child must be rejected before building the pack");
  assertDepartmentSourceEquality(selection, full, report.department, source.problems);
});
