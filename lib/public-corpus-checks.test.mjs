import test from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";

const verifier = fileURLToPath(new URL("../scripts/manuals/verify-public-corpus.mjs", import.meta.url));
test("Public corpus verification accepts pinned ciphertext and rejects tampering or published plaintext", (t) => {
  const root = mkdtempSync(join(tmpdir(), "public-corpus-check-"));
  t.after(() => { assert.ok(root.startsWith(join(tmpdir(), "public-corpus-check-"))); rmSync(root, { recursive: true, force: true }); });
  const revision = "synthetic-v1";
  const keyId = "a".repeat(24);
  const logical = `/__manual_corpus/${revision}/batch-0000.json`;
  const asset = `/__manual_cipher/${revision}/${keyId}/batch-0000.bin`;
  const bytes = Buffer.from("MCPGCM01synthetic ciphertext fixture");
  const sourceHash = "b".repeat(64);
  mkdirSync(join(root, "data/manual-corpus"), { recursive: true });
  mkdirSync(join(root, "public/__manual_cipher", revision, keyId), { recursive: true });
  writeFileSync(join(root, "data/manual-corpus/manifest.json"), JSON.stringify({ revision, batches: [{ path: logical, sha256: sourceHash, bytes: 99 }] }));
  writeFileSync(join(root, "data/manual-corpus/encrypted-assets.json"), JSON.stringify({ schema_version: "manual-assets-aes-gcm-1", algorithm: "AES-256-GCM", compression: "gzip", revision, key_id: keyId, batches: [{ logical_path: logical, asset_path: asset, plaintext_sha256: sourceHash, plaintext_bytes: 99, bytes: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex") }] }));
  const target = join(root, "public", asset);
  writeFileSync(target, bytes);
  const run = () => spawnSync(process.execPath, [verifier], { cwd: root, encoding: "utf8" });
  assert.equal(run().status, 0);
  writeFileSync(target, Buffer.from("MCPGCM01tampered ciphertext fixture"));
  assert.notEqual(run().status, 0);
  writeFileSync(target, bytes);
  mkdirSync(join(root, "public/__manual_corpus"));
  assert.notEqual(run().status, 0);
});
