import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";

import { decodeSidoBoundaries, locateSido } from "./sido-locator.mjs";

const regions = decodeSidoBoundaries(
  JSON.parse(readFileSync(new URL("../public/data/geo/sido-boundaries.json", import.meta.url), "utf8")),
);

// [위도, 경도, 기대 시도] — 시청·군청과 시도 경계 가까운 도시, 섬
const CASES = [
  [37.5665, 126.978, "서울특별시"],
  [37.5035, 126.766, "경기도"], // 부천
  [37.4292, 126.9876, "경기도"], // 과천
  [37.42, 127.1267, "경기도"], // 성남
  [37.4563, 126.7052, "인천광역시"],
  [37.747, 126.488, "인천광역시"], // 강화도
  [37.967, 124.717, "인천광역시"], // 백령도
  [37.8813, 127.7298, "강원특별자치도"], // 춘천
  [37.4912, 129.1245, "강원특별자치도"], // 동해
  [36.6424, 127.489, "충청북도"], // 청주
  [36.8151, 127.1139, "충청남도"], // 천안
  [36.4801, 127.289, "세종특별자치시"],
  [36.3504, 127.3845, "대전광역시"],
  [35.8242, 127.148, "전북특별자치도"], // 전주
  [35.1595, 126.8526, "전남광주통합특별시"], // 광주
  [34.8118, 126.3922, "전남광주통합특별시"], // 목포
  [34.684, 125.435, "전남광주통합특별시"], // 흑산도
  [35.8714, 128.6014, "대구광역시"],
  [36.2428, 128.5728, "대구광역시"], // 군위군(2023년 대구 편입)
  [36.019, 129.3435, "경상북도"], // 포항
  [36.1195, 128.3446, "경상북도"], // 구미
  [37.4845, 130.9057, "경상북도"], // 울릉도
  [35.5384, 129.3114, "울산광역시"],
  [35.228, 128.6811, "경상남도"], // 창원
  [35.1798, 129.075, "부산광역시"],
  [33.4996, 126.5312, "제주특별자치도"], // 제주시
  [33.2541, 126.5601, "제주특별자치도"], // 서귀포시
];

test("GPS 좌표를 2026년 광역시·도로 판별한다", () => {
  for (const [lat, lon, expected] of CASES) {
    assert.equal(locateSido(lat, lon, regions), expected, lat + "," + lon);
  }
});

test("해안에 붙은 좌표는 가까운 시도로, 국외 좌표는 null로 돌려준다", () => {
  assert.equal(locateSido(35.1531, 129.1186, regions), "부산광역시"); // 광안리 해변
  assert.equal(locateSido(33.2465, 126.4118, regions), "제주특별자치도"); // 중문 해안
  assert.equal(locateSido(35.6895, 139.6917, regions), null); // 도쿄
  assert.equal(locateSido(39.0392, 125.7625, regions), null); // 평양
});
