import assert from 'node:assert/strict';
import test from 'node:test';
import { readFileSync } from 'node:fs';
import { activate, manualDatabase, pack, document } from './manuals-test-support.mjs';
import { searchManualSections } from './manuals/search.ts';
const manifest = JSON.parse(readFileSync(new URL('../data/manual-corpus/manifest.json', import.meta.url)));
const batches = manifest.batches.map(batch => JSON.parse(readFileSync(new URL('../data/manual-corpus/assets/' + batch.path, import.meta.url))));
const documentId = 'md-e2925ac8a6658a510921';
const sections = batches.flatMap(batch => batch.sections).filter(row => row.document_id === documentId);
const source = batches.flatMap(batch => batch.documents).find(row => row.document_id === documentId);
test('부부 각각의 급여액 질문은 특례 표와 함께 일반 급여 현황표를 상위에서 제공한다', async (t) => {
    const db = manualDatabase();
    t.after(() => db.sqlite.close());
    await activate(db, pack({ documents: [document({ ...source, section_count: sections.length })], sections }));
    const query = '장애인연금 2026년 부부가 모두 받을 때 기초급여는 각각 얼마인가요?';
    const hits = await searchManualSections(db, query, { limit: 5 });
    assert.ok(hits.slice(0, 5).some(row => row.section_id === '376468842fe1c94ff34c'), JSON.stringify(hits.map(row => [row.section_id, row.title])));
    const specific = await searchManualSections(db, '장애인연금 직역연금 특례 수급자의 기초급여 금액', { limit: 5 });
    assert.ok(specific.some(row => /특례/.test(row.title + ' ' + row.excerpt)));
});
